"""Summarise the HUMAN grades entered in the Stage 6 review CSV. Standard library only; makes no network call; never writes into the grade fields.

    python tools/summarize_human_grades.py                         # reads YOUR copy results/nist_stage6_human_grades.csv (or, if you have none, the blank sheet), writes results/nist_stage6_human_summary.{md,json}
    python tools/summarize_human_grades.py my_graded_copy.csv      # grade in a copy if you prefer
    python tools/summarize_human_grades.py --write-template       # (re)writes the blank layout results/nist_stage6_human_summary_template.md
    python tools/summarize_human_grades.py --check                 # only validates the entries (vocabulary), prints problems, writes nothing
    python tools/summarize_human_grades.py --out-prefix=/tmp/x     # write the summary elsewhere (used by the tests)

Rules:
* Aggregates are computed ONLY from values you typed. A blank cell is "ungraded" and is never guessed, defaulted or inferred from anything else.
* Entries outside the allowed vocabulary stop the run (exit code 2) with the row, column and value; nothing is summarised from an invalid file.
* Three families of numbers are reported separately and never merged: (1) frozen retrieval outcomes, (2) objective format checks of the answers, (3) your human grades.
* Paired counts are raw counts. No p-value, confidence interval or "improvement" claim is computed: N = 24, one generation per query and pipeline.
"""
import csv
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CSV = ROOT / "results" / "nist_stage6_human_review.csv"          # the generated, blank sheet (never grade in it: it is regenerated by the notebook)
GRADES_CSV = ROOT / "results" / "nist_stage6_human_grades.csv"            # YOUR copy with the grades; used by default when it exists
OUT_PREFIX = ROOT / "results" / "nist_stage6_human_summary"
TEMPLATE = ROOT / "results" / "nist_stage6_human_summary_template.md"

VOCAB = {"correct": ("correct", "partially correct", "incorrect"), "supported_by_passages": ("fully supported", "partially supported", "unsupported"),
         "complete": ("complete", "incomplete"), "unsupported_claims": ("none", "present"), "overall_judgment": ("acceptable", "borderline", "unacceptable")}
BETTER = ("a1 better", "a2 better", "neither clearly better")
TAGS = (("a1", "Answer 1 (baseline)"), ("a2", "Answer 2 (re-ranked)"))
CHECKS = ("cites_a_passage", "cites_only_supplied_passages", "cites_a_preregistered_gold_chunk", "is_the_refusal_sentence", "finish_reason_stop", "within_three_sentence_limit")


def norm(v):
    return " ".join((v or "").strip().lower().split())


def load_rows(path):
    with open(path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    need = ["query_id", "lenient_baseline", "lenient_reranked", "strict_baseline", "strict_reranked", "better"] + [f"{t}_{k}" for t, _ in TAGS for k in VOCAB if k != "overall_judgment"] \
        + [f"{t}_overall_judgment" for t, _ in TAGS] + [f"{t}_chk_{c}" for t, _ in TAGS for c in CHECKS]
    missing = [c for c in need if rows and c not in rows[0]]
    if missing:
        raise SystemExit(f"the CSV lacks required columns: {missing}")
    return rows


def validate(rows):
    """-> list of (query_id, column, value, allowed). Blank is allowed (= ungraded)."""
    bad = []
    for r in rows:
        for t, _ in TAGS:
            for k, allowed in VOCAB.items():
                col, v = f"{t}_{k}", norm(r.get(f"{t}_{k}"))
                if v and v not in allowed:
                    bad.append((r["query_id"], col, r[col], allowed))
        v = norm(r.get("better"))
        if v and v not in BETTER:
            bad.append((r["query_id"], "better", r["better"], BETTER))
    return bad


def warnings_for(rows):
    w = []
    for r in rows:
        for t, _ in TAGS:
            if norm(r.get(f"{t}_unsupported_claims")) == "present" and not (r.get(f"{t}_unsupported_claims_notes") or "").strip():
                w.append(f"query {r['query_id']}, {t}: unsupported claims marked 'present' but the notes field is empty")
            if norm(r.get(f"{t}_correct")) == "correct" and norm(r.get(f"{t}_unsupported_claims")) == "present":
                w.append(f"query {r['query_id']}, {t}: graded 'correct' while unsupported claims are 'present' (allowed, please double-check)")
            if norm(r.get(f"{t}_overall_judgment")) and not (r.get(f"{t}_justification") or "").strip():
                w.append(f"query {r['query_id']}, {t}: overall judgment has no justification")
    return w


def count(rows, col, allowed):
    c = Counter(norm(r.get(col)) for r in rows)
    out = {a: c.get(a, 0) for a in allowed}
    out["ungraded"] = c.get("", 0)
    return out


def summarize(rows):
    n = len(rows)
    S = dict(n_queries=n)
    # (1) frozen retrieval outcomes: copied from the review file; not human grades
    S["retrieval_frozen"] = {rule: {pipe: dict(Counter(r[f"{rule}_{pipe}"] for r in rows)) for pipe in ("baseline", "reranked")} for rule in ("lenient", "strict")}
    # (2) objective format checks: copied; NOT evidence of correctness
    S["objective_format_checks"] = {t: {c: sum(r[f"{t}_chk_{c}"] == "True" for r in rows) for c in CHECKS} for t, _ in TAGS}
    # (3) human grades
    S["human"] = {t: {k: count(rows, f"{t}_{k}", allowed) for k, allowed in VOCAB.items()} for t, _ in TAGS}
    S["human"]["better"] = count(rows, "better", BETTER)
    graded = lambda r, t: norm(r.get(f"{t}_correct")) in VOCAB["correct"]
    both = [r for r in rows if graded(r, "a1") and graded(r, "a2")]
    S["paired"] = dict(n_pairs_with_both_correctness_graded=len(both), n_pairs_ungraded_or_incomplete=n - len(both))
    cross = {a: {b: [] for b in VOCAB["correct"]} for a in VOCAB["correct"]}
    for r in both:
        cross[norm(r["a1_correct"])][norm(r["a2_correct"])].append(r["query_id"])
    S["paired"]["crosstab_a1_rows_by_a2_columns"] = {a: {b: len(v) for b, v in row.items()} for a, row in cross.items()}
    cat = {"both correct": [], "only Answer 1 correct": [], "only Answer 2 correct": [], "both incorrect": [], "other (no 'correct'; at least one 'partially correct')": []}
    for r in both:
        a, b = norm(r["a1_correct"]), norm(r["a2_correct"])
        key = ("both correct" if a == b == "correct" else "only Answer 1 correct" if a == "correct" else "only Answer 2 correct" if b == "correct"
               else "both incorrect" if a == b == "incorrect" else "other (no 'correct'; at least one 'partially correct')")
        cat[key].append(r["query_id"])
    S["paired"]["categories"] = {k: dict(n=len(v), query_ids=v) for k, v in cat.items()}
    S["paired"]["discordant_raw_counts"] = dict(only_answer_1_correct=len(cat["only Answer 1 correct"]), only_answer_2_correct=len(cat["only Answer 2 correct"]),
                                                note="raw counts only: no test statistic, p-value or confidence interval is computed")
    S["paired"]["better_by_query"] = {k: [r["query_id"] for r in rows if norm(r.get("better")) == k] for k in BETTER}
    # descriptive views (not inference)
    fail = [r for r in rows if r["lenient_baseline"] != "success" or r["strict_baseline"] != "success"]
    S["failure_cases_individually"] = [dict(query_id=r["query_id"], category=r["category"], lenient=f"{r['lenient_baseline']} -> {r['lenient_reranked']}", strict=f"{r['strict_baseline']} -> {r['strict_reranked']}",
                                            a1_correct=norm(r.get("a1_correct")) or "ungraded", a2_correct=norm(r.get("a2_correct")) or "ungraded", better=norm(r.get("better")) or "ungraded") for r in fail]
    S["correctness_by_baseline_lenient_retrieval_outcome_descriptive"] = {
        stratum: {t: count([r for r in rows if (r["lenient_baseline"] == "success") == (stratum == "baseline retrieval success")], f"{t}_correct", VOCAB["correct"]) for t, _ in TAGS}
        for stratum in ("baseline retrieval success", "baseline retrieval stumble or miss")}
    S["warnings"] = warnings_for(rows)
    S["n_rows_fully_graded"] = sum(all(norm(r.get(f"{t}_{k}")) for t, _ in TAGS for k in VOCAB) and norm(r.get("better")) != "" for r in rows)
    return S


def render_md(S, template=False, source=""):
    f = (lambda x: "____") if template else (lambda x: str(x))
    n = S["n_queries"]
    L = ["# Stage 6 human-grade summary" + (" (blank template)" if template else ""), "",
         ("This is the empty layout. Run `python tools/summarize_human_grades.py` after entering your grades; every cell below is then computed ONLY from the values you typed." if template
          else f"Computed from `{source}`. Every number in section C is computed ONLY from explicit human-entered values; a blank cell is counted as *ungraded*, never guessed."), "",
         "**Three separate metrics. They are never merged:** (A) frozen retrieval outcomes, (B) objective format checks, (C) your human grades of the answers.", "",
         "No significance test is computed. N = 24 queries, one generation per query and pipeline, one grader (see the limitations notes).", ""]
    L += ["## A. Retrieval success (frozen Stage 4/5 result; not a human grade)", "", "| rule | pipeline | success | stumble | miss |", "|---|---|---|---|---|"]
    for rule in ("lenient", "strict"):
        for pipe in ("baseline", "reranked"):
            c = S["retrieval_frozen"][rule][pipe]
            L.append(f"| {rule} | {pipe} | {c.get('success', 0)} | {c.get('stumble', 0)} | {c.get('miss', 0)} |")
    L += ["", "## B. Objective format checks of the answers (automatic; NOT evidence of factual correctness)", "", "| check | Answer 1 (baseline) | Answer 2 (re-ranked) |", "|---|---|---|"]
    for c in CHECKS:
        L.append(f"| {c.replace('_', ' ')} | {S['objective_format_checks']['a1'][c]} / {n} | {S['objective_format_checks']['a2'][c]} / {n} |")
    L += ["", "## C. Human grades (from the values you entered)", ""]
    for k, title in (("correct", "Correctness"), ("supported_by_passages", "Evidence support (against the passages shown to that answer)"), ("complete", "Completeness"),
                     ("unsupported_claims", "Unsupported claims"), ("overall_judgment", "Overall judgment")):
        allowed = list(VOCAB[k]) + ["ungraded"]
        L += [f"### C.{ {'correct': 1, 'supported_by_passages': 2, 'complete': 3, 'unsupported_claims': 4, 'overall_judgment': 5}[k] } {title}", "", "| pipeline | " + " | ".join(allowed) + " |", "|---|" + "---|" * len(allowed)]
        for t, name in TAGS:
            L.append(f"| {name} | " + " | ".join(f(S["human"][t][k][a]) for a in allowed) + " |")
        L.append("")
    L += ["### C.6 Paired judgment (`better`)", "", "| A1 better | A2 better | neither clearly better | ungraded |", "|---|---|---|---|",
          "| " + " | ".join(f(S["human"]["better"][a]) for a in list(BETTER) + ["ungraded"]) + " |", ""]
    P = S["paired"]
    L += ["### C.7 Paired correctness (queries where BOTH answers have a correctness grade)", "", f"Pairs with both graded: {f(P['n_pairs_with_both_correctness_graded'])} of {n}.", "",
          "| category | number of queries | query ids |", "|---|---|---|"]
    for k, v in P["categories"].items():
        L.append(f"| {k} | {f(v['n'])} | {'' if template else ', '.join(v['query_ids'])} |")
    L += ["", "Cross-tab (rows = Answer 1 grade, columns = Answer 2 grade):", "", "| A1 \\ A2 | " + " | ".join(VOCAB["correct"]) + " |", "|---|---|---|---|"]
    for a in VOCAB["correct"]:
        L.append(f"| {a} | " + " | ".join(f(P["crosstab_a1_rows_by_a2_columns"][a][b]) for b in VOCAB["correct"]) + " |")
    L += ["", "Cases the grader marked: " + ("" if template else "; ".join(f"{k}: {', '.join(v) or 'none'}" for k, v in P["better_by_query"].items())), ""]
    L += ["## D. Descriptive views (not inference)", "", "### D.1 The retrieval failure cases, one by one", "", "| query | category | lenient (base -> rerank) | strict | Answer 1 correct? | Answer 2 correct? | better |", "|---|---|---|---|---|---|---|"]
    for r in S["failure_cases_individually"]:
        L.append(f"| {r['query_id']} | {r['category']} | {r['lenient']} | {r['strict']} | " + ("____ | ____ | ____ |" if template else f"{r['a1_correct']} | {r['a2_correct']} | {r['better']} |"))
    L += ["", "### D.2 Human correctness split by the baseline's retrieval outcome", "", "| stratum | pipeline | " + " | ".join(list(VOCAB["correct"]) + ["ungraded"]) + " |", "|---|---|---|---|---|---|"]
    for stratum, d in S["correctness_by_baseline_lenient_retrieval_outcome_descriptive"].items():
        for t, name in TAGS:
            L.append(f"| {stratum} | {name} | " + " | ".join(f(d[t][a]) for a in list(VOCAB["correct"]) + ["ungraded"]) + " |")
    L += ["", "## E. Entry problems", "", "(none)" if template or not S["warnings"] else "\n".join(f"* {w}" for w in S["warnings"]), ""]
    return "\n".join(L)


def main(argv):
    args = [a for a in argv if not a.startswith("--")]
    opt = {a.split("=", 1)[0]: a.split("=", 1)[1] for a in argv if a.startswith("--") and "=" in a}
    if "--write-template" in argv:
        TEMPLATE.write_text(render_md(summarize(load_rows(DEFAULT_CSV)), template=True), encoding="utf-8")      # A and B are frozen/objective facts; every human-grade cell is blanked
        print("wrote", TEMPLATE)
        return 0
    path = Path(args[0]) if args else (GRADES_CSV if GRADES_CSV.exists() else DEFAULT_CSV)
    rows = load_rows(path)
    bad = validate(rows)
    if bad:
        print("INVALID ENTRIES: nothing was summarised.")
        for q, col, val, allowed in bad:
            print(f"  query {q}, column {col}: {val!r} is not one of {list(allowed)} (blank = ungraded)")
        return 2
    if "--check" in argv:
        S = summarize(rows)
        print(f"vocabulary OK; {S['n_rows_fully_graded']} of {len(rows)} rows fully graded; warnings: {len(S['warnings'])}")
        for w in S["warnings"]:
            print("  warning:", w)
        return 0
    S = summarize(rows)
    S["input"] = dict(csv=str(path), sha256=hashlib.sha256(Path(path).read_bytes()).hexdigest())
    md = render_md(S, source=str(path))
    prefix = Path(opt["--out-prefix"]) if "--out-prefix" in opt else OUT_PREFIX
    Path(str(prefix) + ".md").write_text(md + "\n", encoding="utf-8")
    Path(str(prefix) + ".json").write_text(json.dumps(S, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(md)
    print(f"\nwrote {prefix}.md and {prefix}.json (input sha256 {S['input']['sha256'][:16]}...)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
